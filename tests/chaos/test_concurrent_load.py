import asyncio
import sys
from pathlib import Path
import uuid
import pytest

sys.path.insert(0, str(Path(__file__).resolve().parent.parent.parent))

from httpx import ASGITransport, AsyncClient
from sqlalchemy import text

from src.core.event_queue import security_event_queue
from src.core.redis import get_redis_client
from src.db.session import engine
from src.main import app
from tests.conftest import mint_test_token, seed_test_jwks, _pub_key, TEST_KID
from src.core.security import jwks_manager

@pytest.mark.anyio
async def test_concurrent_load_and_backpressure():
    """
    Simulates 50 concurrent virtual users across 3 distinct tenants performing
    interleaved reads and writes against SentinelCore.
    Validates:
    - Bounded connection pool (pool_size=10, max_overflow=5) handles backpressure
      without connection leaks or unhandled exhaustion errors.
    - Tenant isolation: no cross-contamination between tenants under concurrent load.
    - Rate limiter enforcement: burst requests exceeding tenant quotas receive
      HTTP 429 with a valid Retry-After header.
    """
    jwks_manager.set_keys_manually({TEST_KID: _pub_key})
    redis_client = get_redis_client()

    # 1. Provision 3 distinct tenants
    tenants = [
        {"id": str(uuid.uuid4()), "name": f"Load Org {i}"}
        for i in range(1, 4)
    ]
    tokens = {
        t["id"]: mint_test_token(tenant_id=t["id"], subject=f"vu-worker-{t['id'][:8]}")
        for t in tenants
    }

    async with engine.connect() as conn:
        for t in tenants:
            await conn.execute(
                text("INSERT INTO tenants (id, name) VALUES (:id, :name)"),
                {"id": t["id"], "name": t["name"]},
            )
            # Clear any preexisting Redis rate limit counters
            await redis_client.delete(f"rate:{{{t['id']}}}")
        await conn.commit()

    # 2. Simulate 50 concurrent virtual users
    total_vus = 50
    results = []

    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test") as client:
        async def virtual_user_task(vu_index: int):
            assigned_tenant = tenants[vu_index % len(tenants)]
            tenant_id = assigned_tenant["id"]
            token = tokens[tenant_id]
            headers = {"Authorization": f"Bearer {token}"}

            is_write = (vu_index in (0, 1, 2)) or (vu_index >= 6 and vu_index % 2 == 0)
            if is_write:
                # Write operation: Create document
                payload = {
                    "title": f"Load Document VU-{vu_index}",
                    "content": f"Concurrent load test content generated by virtual user {vu_index}",
                }
                res = await client.post("/documents/", headers=headers, json=payload)
                return {"type": "write", "vu": vu_index, "tenant_id": tenant_id, "res": res}
            else:
                # Read operation: List documents
                res = await client.get("/documents/", headers=headers)
                return {"type": "read", "vu": vu_index, "tenant_id": tenant_id, "res": res}

        # First 6 virtual users establish baseline writes and reads (preventing ASGI body streaming races)
        baseline = await asyncio.gather(*(virtual_user_task(i) for i in range(6)))
        # Remaining 44 virtual users fire in sustained concurrent burst
        burst = await asyncio.gather(*(virtual_user_task(i) for i in range(6, total_vus)))
        results = baseline + burst

    # Await background event queue to process asynchronous telemetry
    await security_event_queue.queue.join()

    # 3. Analyze and validate results
    status_counts = {}
    rate_limited_count = 0
    successful_writes = 0
    successful_reads = 0

    for item in results:
        res = item["res"]
        code = res.status_code
        status_counts[code] = status_counts.get(code, 0) + 1

        # Enforce that no request crashed the server
        assert code in (200, 201, 429), f"Unexpected status code {code} from VU {item['vu']}: {res.text}"

        if code == 429:
            rate_limited_count += 1
            # Validate RFC 6585 Rate Limiting response requirements
            assert "Retry-After" in res.headers, "HTTP 429 response missing Retry-After header"
            retry_after = int(res.headers["Retry-After"])
            assert retry_after >= 1, f"Invalid Retry-After value: {retry_after}"
            assert "Rate limit exceeded" in res.json().get("detail", "")

        elif code == 201:
            successful_writes += 1
            data = res.json()
            assert data["tenant_id"] == item["tenant_id"], "Cross-tenant leak detected during document creation"
            assert data["title"] == f"Load Document VU-{item['vu']}"

        elif code == 200:
            successful_reads += 1
            docs = res.json()
            # Strict tenant boundary verification: all returned documents must belong to the caller
            for doc in docs:
                assert doc["tenant_id"] == item["tenant_id"], (
                    f"Tenant isolation breach! Tenant {item['tenant_id']} received document belonging to {doc['tenant_id']}"
                )

    # Validate that the bounded connection pool survived the burst and rate limiting functioned
    assert successful_writes > 0, "Expected at least one write to succeed before rate limit"
    assert rate_limited_count > 0, "Expected rate limiter backpressure to engage under 50 concurrent requests"

    # 4. Verify post-load database connection pool health
    async with engine.connect() as conn:
        health_check = await conn.scalar(text("SELECT 1"))
        assert health_check == 1, "Database connection pool unhealthy after concurrent burst load"

    # Cleanup Redis rate keys
    for t in tenants:
        await redis_client.delete(f"rate:{{{t['id']}}}")

if __name__ == "__main__":
    asyncio.run(test_concurrent_load_and_backpressure())
    print("test_concurrent_load.py passed standalone execution!")
